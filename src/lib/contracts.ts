const BRAND = "Atmos Media";

/**
 * The Atmos side of the parties line: "Example Limited (NZBN 9429000000000),
 * trading as Atmos Media", or just the brand until a legal entity is set.
 */
export function atmosParty({
  legalEntity,
  nzbn,
}: Pick<ContractSettings, "legalEntity" | "nzbn">): string {
  if (!legalEntity) return BRAND;
  return `${legalEntity}${nzbn ? ` (NZBN ${nzbn})` : ""}, trading as ${BRAND}`;
}

/** The defaults for a contract generated by `adminName` under `settings`. */
export function contractDefaults(
  settings: ContractSettings,
  adminName: string,
): ContractDefaults {
  return {
    atmosParty: atmosParty(settings),
    // Whoever generates the contract is its Atmos contact by default.
    atmosContact: [adminName, settings.contactPhone].filter(Boolean).join(", "),
    version: settings.versionLabel || CONTRACT_VERSION,
    defaultBond: settings.defaultBond,
  };
}

